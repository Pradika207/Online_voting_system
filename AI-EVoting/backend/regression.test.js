test('NOTA is present and distinguished in the candidate model', async () => {
  const res = await apiRequest(`/api/candidates?electionId=${electionId}`, {
    method: 'GET',
  });
  assert.equal(res.status, 200, `Candidate listing failed: ${JSON.stringify(res.body)}`);
  const candidates = Array.isArray(res.body) ? res.body : [];
  const notaCandidate = candidates.find((candidate) => Number(candidate.is_nota) === 1);
  assert.ok(notaCandidate, 'NOTA candidate should exist for the election');
  assert.notEqual(notaCandidate.name, 'Regression Candidate', 'NOTA should be distinct from a normal candidate');
});

test('database schema preserves separation between eligibility and ballots', async () => {
  const tables = await getDbRows("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name");
  const tableNames = tables.map((row) => row.name);

  assert.ok(tableNames.includes('election_eligibility'), 'Eligibility table should exist');
  assert.ok(tableNames.includes('ballots'), 'Ballots table should exist');
  assert.ok(tableNames.includes('receipts'), 'Receipts table should exist');

  const fkRows = await getDbRows("PRAGMA foreign_key_list('ballots')");
  const eligibilityFkRows = await getDbRows("PRAGMA foreign_key_list('election_eligibility')");
  assert.ok(fkRows.length > 0, 'Ballots should reference an election via foreign key');
  assert.ok(eligibilityFkRows.length > 0, 'Eligibility should reference voter/election via foreign keys');

  const uniqueReceiptIndex = await getDbRows("PRAGMA index_list('receipts')");
  const uniqueBallotHash = await getDbRows("PRAGMA index_list('ballots')");
  assert.ok(uniqueReceiptIndex.length >= 1, 'Receipt database indexes should exist');
  assert.ok(uniqueBallotHash.length >= 1, 'Ballot hash indexing should exist');
});

