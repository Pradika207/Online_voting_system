test('XSS-safe and oversized request paths still reject unsafe input', async () => {
  const xssRes = await apiRequest('/api/admin/candidates', {
    method: 'POST',
    headers: { Authorization: `Bearer ${adminToken}` },
    body: JSON.stringify({
      name: '<script>alert(1)</script>',
      party: 'Script',
      manifesto: '<img src=x onerror=alert(1)>',
      electionId,
    }),
  });
  assert.ok(xssRes.status === 400 || xssRes.status === 200, 'XSS-like candidate values should not crash the server');

  const oversized = await apiRequest('/api/admin/elections', {
    method: 'POST',
    headers: { Authorization: `Bearer ${adminToken}` },
    body: JSON.stringify({
      name: 'A'.repeat(10000),
      description: 'B'.repeat(900000),
      startDate: '2099-01-01T00:00:00.000Z',
      endDate: '2099-01-02T00:00:00.000Z',
      status: 'upcoming',
    }),
  });
  assert.ok(oversized.status === 413 || oversized.status === 400, 'Oversized request bodies should be rejected');
});

test('ballot encryption and integrity checks are internally consistent', () => {
  const key = crypto.randomBytes(32);
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  const payload = JSON.stringify({ version: 1, candidateId: 42 });
  const ciphertext = Buffer.concat([cipher.update(payload), cipher.final()]);
  const authTag = cipher.getAuthTag();
  const electionId = 7;

  const hash = crypto.createHash('sha256')
    .update(`${electionId}.${iv.toString('base64')}.${ciphertext.toString('base64')}.${authTag.toString('base64')}`)
    .digest('hex');

  assert.ok(hash.length === 64, 'Ballot hash should be a SHA-256 digest');
  assert.doesNotMatch(hash, /candidateId|version/i, 'Ballot hash should not leak plaintext data');
});
